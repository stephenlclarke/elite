/// Versioned native geometry adaptation of Rescue Stations 1.5.4.
/// Numeric mesh derivatives retain CC BY-NC-SA 3.0; see the adapter provenance document.
struct NativeStationGeometry: Sendable {
  enum Kind: String, Codable, Sendable, CaseIterable {
    case waystation, headquarters
    var sourceDefinition: String { self == .waystation ? "rescue_station" : "rrs_headquarters" }
    var sourceRoles: [String] {
      [self == .waystation ? "rescue_station" : "rrs_galactic_hq", "rrs_group_spacestation"]
    }
  }

  struct Bounds: Sendable, Equatable {
    let minimum: Vector3
    let maximum: Vector3
    func support(_ direction: Vector3) -> Double {
      Vector3(
        direction.x >= 0 ? maximum.x : minimum.x,
        direction.y >= 0 ? maximum.y : minimum.y,
        direction.z >= 0 ? maximum.z : minimum.z
      ).dot(direction)
    }
  }

  struct Port: Sendable, Equatable {
    let center: Vector3
    let outward: Vector3
    let up: Vector3
    let tunnelDepth: Double
    let aperture: [Vector3]

    /// Convex aperture containment proves the whole aligned mesh's transverse projection fits.
    /// It does not prove an approach through the station, or clearance from another actor.
    func fits(_ player: Mesh, margin: Double = 0) -> Bool {
      guard margin.isFinite, margin >= 0, player.vertices.count >= 4,
        player.vertices.allSatisfy({ $0.finiteStationVector }),
        player.vertices.contains(where: { $0.length > 0 }), player.faces.count >= 4,
        player.faces.allSatisfy({ face in
          face.count >= 3 && face.allSatisfy { player.vertices.indices.contains($0) }
        })
      else { return false }
      for index in aperture.indices {
        let a = aperture[index]
        let b = aperture[(index + 1) % aperture.count]
        let edge = b - a
        let length = edge.length
        guard length > 0 else { return false }
        // The aperture is counterclockwise in the port's x/y plane.
        for vertex in player.vertices {
          let distance = (edge.x * (vertex.y - a.y) - edge.y * (vertex.x - a.x)) / length
          guard distance > margin else { return false }
        }
      }
      return true
    }
  }

  struct Exit: Sendable, Equatable {
    let center: Vector3
    let direction: Vector3
    let orientation: Basis3
    let clearance: Double
  }

  static let adapterRevision = "rrs-native-geometry-v1"
  static let sourceVersion = "1.5.4"
  static let archiveSHA256 = "c3d6ba5b46e7d09865f57ec96d6741c4b53477cbdf641f9aaf44e601f3dea70c"
  let kind: Kind
  let mesh: Mesh
  let bounds: Bounds
  let docking: Port
  let launch: Port

  static let waystation = make(.waystation)
  static let headquarters = make(.headquarters)

  /// Proper Y180 rotation, not a reflection. Surface conventions are adapted at assembly.
  static func nativePoint(_ source: Vector3) -> Vector3 { .init(-source.x, source.y, -source.z) }

  /// World distance compression is independent of source model-unit geometry.
  /// HQ's source 500000 separation maps to the existing native arrival/main separation.
  func position(in anchors: SystemAnchors) -> Vector3? {
    let planet = anchors.planet.position
    let sun = anchors.sun.position
    guard planet.finiteStationVector, sun.finiteStationVector,
      anchors.station.position == Vector3(0, 0, 0), anchors.arrival.finiteStationVector,
      anchors.planet.radius.isFinite, anchors.planet.radius > 0,
      anchors.sun.radius.isFinite, anchors.sun.radius > 0,
      planet.length > 0, sun.length > 0
    else { return nil }
    let point: Vector3
    switch kind {
    case .waystation:
      let halfPlanet = planet * 0.5
      point = halfPlanet * 0.7 + sun * (halfPlanet.length / sun.length * 0.3)
    case .headquarters:
      let cross = sun.cross(planet)
      let distance = (anchors.arrival - anchors.station.position).length
      guard cross.length > 1e-9, distance.isFinite, distance > 0 else { return nil }
      point = cross * (500000 * (distance / 500000) / cross.length)
    }
    let radius = mesh.vertices.map(\.length).max() ?? .infinity
    guard point.finiteStationVector, radius.isFinite,
      (point - planet).length > anchors.planet.radius + radius,
      (point - sun).length > anchors.sun.radius + radius,
      point.length > radius
    else { return nil }
    return point
  }

  /// Analytic separating-plane proof: every player vertex is beyond the complete
  /// structural station bound, and motion along direction only increases separation.
  /// Runtime must separately sweep against all other scene actors and celestials.
  func exit(for player: Mesh, clearance: Double = 1000) -> Exit? {
    guard launch.fits(player), clearance.isFinite, clearance > 0 else { return nil }
    let direction = launch.outward
    var orientation = Basis3()
    orientation.x = .init(direction.z, 0, 0)
    orientation.z = direction
    let rear = player.vertices.map { orientation.apply($0).dot(direction) }.min()!
    let distance = bounds.support(direction) - launch.center.dot(direction) - rear + clearance
    guard distance.isFinite, distance > 0 else { return nil }
    return .init(
      center: launch.center + direction * distance,
      direction: direction, orientation: orientation, clearance: clearance)
  }

  private static func make(_ kind: Kind) -> Self {
    let mesh = StationSourceMesh.assembled(kind)
    let minimum = Vector3(
      mesh.vertices.map(\.x).min()!, mesh.vertices.map(\.y).min()!,
      mesh.vertices.map(\.z).min()!)
    let maximum = Vector3(
      mesh.vertices.map(\.x).max()!, mesh.vertices.map(\.y).max()!,
      mesh.vertices.map(\.z).max()!)
    let rectangle = [
      Vector3(-125, -62.5, 0), .init(125, -62.5, 0),
      .init(125, 62.5, 0), .init(-125, 62.5, 0),
    ]
    // The liner mouth is wider than the main body's bore. The whole hull must
    // fit the narrowest real cross-section before a docking approach can begin.
    let octagon = [
      Vector3(106.72374, -44.20642, 0), .init(106.72374, 44.20642, 0),
      .init(44.20642, 106.72374, 0), .init(-44.20642, 106.72374, 0),
      .init(-106.72374, 44.20642, 0), .init(-106.72374, -44.20642, 0),
      .init(-44.20642, -106.72374, 0), .init(44.20642, -106.72374, 0),
    ]
    let docking = Port(
      center: nativePoint(
        kind == .waystation
          ? .init(0, 0, 350)
          : .init(-250, 86.5, 1860.8)), outward: .init(0, 0, -1), up: .init(0, 1, 0),
      tunnelDepth: kind == .waystation ? 140 : 350,
      aperture: kind == .waystation ? octagon : rectangle)
    let launch =
      kind == .waystation
      ? Port(
        center: nativePoint(.init(0, 0, -350)), outward: .init(0, 0, 1),
        up: .init(0, 1, 0), tunnelDepth: 140, aperture: octagon) : docking
    return .init(
      kind: kind, mesh: mesh, bounds: .init(minimum: minimum, maximum: maximum),
      docking: docking, launch: launch)
  }
}

extension Vector3 {
  fileprivate var finiteStationVector: Bool {
    [x, y, z].allSatisfy { $0.isFinite && abs($0) <= 1e12 }
  }
}

/// Source structural meshes only. Parked display ships, flashers and force-field art
/// are deliberately not solid actors in this native adaptation. No textures are embedded.
private enum StationSourceMesh {
  static func assembled(_ kind: NativeStationGeometry.Kind) -> Mesh {
    var vertices: [Vector3] = []
    var faces: [[Int]] = []
    func append(
      _ mesh: Mesh, offset: Vector3 = .init(0, 0, 0), reverse: Bool = false,
      reverseWinding: Bool
    ) {
      let base = vertices.count
      vertices += mesh.vertices.map { point in
        let local = reverse ? Vector3(point.x, -point.y, -point.z) : point
        return NativeStationGeometry.nativePoint(local + offset)
      }
      faces += mesh.faces.map { face in
        let oriented = reverseWinding ? Array(face.reversed()) : face
        return oriented.map { $0 + base }
      }
    }
    switch kind {
    case .waystation:
      // The closed genus-one source body has inward signed orientation.
      // Reverse its complete connected surface, preserving its genuine tunnel.
      append(waystation, reverseWinding: true)
      // These open liners face away from their bore in the source convention.
      // Native interiors must face the entering pilot; their mouths stay open.
      append(waystationDock, offset: .init(0, 0, 280), reverseWinding: true)
      append(waystationDock, offset: .init(0, 0, -280), reverse: true, reverseWinding: true)
    case .headquarters:
      // Independent closed-asteroid and open-front-face witnesses establish
      // each component's native convention; no centroid repair fills openings.
      append(headquartersAsteroid, reverseWinding: true)
      append(headquartersConstruction, reverseWinding: true)
      for y in [836.5, 86.5] {
        for x in [750.0, 250.0, -250.0, -750.0] {
          // The five-sided source bay's side/back faces point out of its interior.
          append(headquartersBay, offset: .init(x, y, 1685.8), reverseWinding: true)
        }
      }
    }
    return Mesh(vertices: vertices, faces: faces, preserveWinding: true)
  }

